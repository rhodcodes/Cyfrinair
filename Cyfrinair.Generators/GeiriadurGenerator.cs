using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Cyfrinair.Generators;

[Generator]
public sealed class GeiriadurGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<AdditionalText> geiriadurFiles = context.AdditionalTextsProvider
            .Where(static file => Path.GetFileName(file.Path).Equals("Geiriadur.txt", StringComparison.OrdinalIgnoreCase));

        IncrementalValueProvider<ImmutableArray<string>> wordsProvider = geiriadurFiles
            .Select(static (file, cancellationToken) =>
            {
                SourceText? text = file.GetText(cancellationToken);

                if (text is null)
                {
                    return ImmutableArray<string>.Empty;
                }

                return [
                    ..text.Lines
                        .Select(line => line.ToString().Trim())
                        .Where(line => line.Length > 0)
                        .Where(line => !line.StartsWith("#", StringComparison.Ordinal))
                        .Distinct(StringComparer.Ordinal)
                ];
            })
            .Collect()
            .Select(static (wordLists, _) => wordLists.SelectMany(words => words).ToImmutableArray());

        context.RegisterSourceOutput(wordsProvider, static (sourceProductionContext, words) =>
        {
            string source = GenerateSource(words);
            sourceProductionContext.AddSource("Passphrase.Geiriadur.g.cs", source);
        });
    }

    private static string GenerateSource(ImmutableArray<string> words)
    {
        StringBuilder builder = new();

        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("using System.Collections.Immutable;");
        builder.AppendLine();
        builder.AppendLine("namespace Cyfrinair.Core;");
        builder.AppendLine();
        builder.AppendLine("public partial class Passphrase");
        builder.AppendLine("{");
        builder.AppendLine("    private static readonly ImmutableArray<string> _wordList =");
        builder.AppendLine("    [");

        foreach (string word in words)
        {
            builder.Append("        \"");
            builder.Append(EscapeStringLiteral(word));
            builder.AppendLine("\",");
        }

        builder.AppendLine("    ];");
        builder.AppendLine("}");

        return builder.ToString();
    }

    private static string EscapeStringLiteral(string value)
    {
        return value
            .Replace("\\", "\\\\")
            .Replace("\"", "\\\"")
            .Replace("\r", "\\r")
            .Replace("\n", "\\n")
            .Replace("\t", "\\t");
    }
}